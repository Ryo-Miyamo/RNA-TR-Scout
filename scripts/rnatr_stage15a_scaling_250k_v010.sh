#!/usr/bin/env bash
set -euo pipefail

WRAPPER_VERSION="rnatr_stage15a_scaling_250k_wrapper_v0.1.0"
PAYLOAD_SHA256="d9fc3bc4828496aba80d2fcea5295ec396b7f72f9281430fd7b9b562bb4dde2d"
PAYLOAD_BYTES="83046"
SELF="$(readlink -f "${BASH_SOURCE[0]}")"

for tool in awk sed base64 sha256sum tar mktemp; do
    command -v "$tool" >/dev/null 2>&1 || {
        echo "ERROR: required tool not found: $tool" >&2
        exit 2
    }
done

tmp="$(mktemp -d)"
cleanup() {
    rm -rf "$tmp"
}
trap cleanup EXIT

begin_line="$(awk '/^__RNATR_STAGE15A_250K_PAYLOAD_BEGIN__$/{print NR; exit}' "$SELF")"
end_line="$(awk '/^__RNATR_STAGE15A_250K_PAYLOAD_END__$/{print NR; exit}' "$SELF")"
[[ -n "$begin_line" && -n "$end_line" && "$end_line" -gt "$begin_line" ]] || {
    echo "ERROR: embedded payload markers not found" >&2
    exit 2
}

payload="$tmp/payload.tar.gz"
sed -n "$((begin_line + 1)),$((end_line - 1))p" "$SELF" | base64 -d > "$payload"

observed_bytes="$(stat -c '%s' "$payload")"
observed_sha="$(sha256sum "$payload" | awk '{print $1}')"
[[ "$observed_bytes" == "$PAYLOAD_BYTES" ]] || {
    echo "ERROR: embedded payload byte count mismatch: $observed_bytes != $PAYLOAD_BYTES" >&2
    exit 2
}
[[ "$observed_sha" == "$PAYLOAD_SHA256" ]] || {
    echo "ERROR: embedded payload SHA-256 mismatch: $observed_sha != $PAYLOAD_SHA256" >&2
    exit 2
}

work="$tmp/bundle"
mkdir -p "$work"
tar -xzf "$payload" -C "$work"
cd "$work"
sha256sum -c SHA256SUMS

export RNATR_STAGE15A_SELF="$SELF"
echo
printf 'wrapper_version\t%s\n' "$WRAPPER_VERSION"
printf 'payload_sha256\t%s\n' "$PAYLOAD_SHA256"
printf 'payload_integrity\tPASS\n'
exec bash ./install_and_run_stage15a_scaling_250k_v0.1.0.sh

