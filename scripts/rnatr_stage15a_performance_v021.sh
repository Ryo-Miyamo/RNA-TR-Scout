find_python() {
    local candidate
    for candidate in \
        "${CONDA_PREFIX:-}/bin/python" \
        "/home/tokushimaneuro02/miniconda3/envs/rnatr-v03/bin/python"
    do
        [[ -n "$candidate" && -x "$candidate" ]] || continue
        if "$candidate" - <<'PY' >/dev/null 2>&1
import pysam
parts = tuple(int(x) for x in pysam.__version__.split('.')[:2])
assert parts >= (0, 24)
PY
        then
            printf '%s\n' "$candidate"
            return 0
        fi
    done
    return 1
}

metric() {
    local path="$1"
    local key="$2"
    awk -F '\t' -v key="$key" '$1==key {print $2}' "$path" | tail -n1 | tr -d '\015'
}

main() {
    extract_payload

    [[ "$PROJECT_ROOT" == "/mnt/intelssd/rnatr_project" ]] || fail "unexpected project root"
    [[ -s "$PROJECT_ROOT/config/paths.env" ]] || fail "paths.env missing"
    [[ -s "$V0201_QC" ]] || fail "v0.2.0.1 success QC missing: $V0201_QC"
    [[ "$(metric "$V0201_QC" audit_status)" == "PASS" ]] || fail "v0.2.0.1 audit is not PASS"
    [[ "$(metric "$V0201_QC" package_exact_logical_parity)" == "true" ]] || fail "v0.2.0.1 logical parity is not true"
