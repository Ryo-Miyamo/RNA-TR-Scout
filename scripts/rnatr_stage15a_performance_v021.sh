    [[ ! -e "$RESULT_ROOT" ]] || fail "v0.2.1 result root already exists; preserve it: $RESULT_ROOT"
    [[ ! -e "$QC_ROOT" ]] || fail "v0.2.1 QC root already exists; preserve it: $QC_ROOT"
    for output in "$SUCCESS_BUNDLE" "$SUCCESS_BUNDLE.sha256" "$FAILURE_BUNDLE" "$FAILURE_BUNDLE.sha256"; do
        [[ ! -e "$output" ]] || fail "refusing to overwrite: $output"
    done

    local PYTHON_BIN CPU_COUNT RUNNER_SRC DOC_SRC DIFF_SRC
    PYTHON_BIN="$(find_python)" || fail "rnatr-v03 Python with pysam >=0.24 not found"
    CPU_COUNT="$(nproc)"
    (( CPU_COUNT >= 24 )) || fail "at least 24 visible CPUs required; found $CPU_COUNT"
    command -v samtools >/dev/null 2>&1 || fail "samtools not found"
    command -v pigz >/dev/null 2>&1 || fail "pigz not found"
    [[ -x /usr/bin/time ]] || fail "/usr/bin/time not found"

    RUNNER_SRC="$BUNDLE_DIR/scripts/rnatr_stage15a_run_performance_100k_v0.2.1.py"
    DOC_SRC="$BUNDLE_DIR/docs/RNA_TR_Scout_Stage15A_performance_critical_path_v0.2.1.md"
    DIFF_SRC="$BUNDLE_DIR/rnatr_stage15a_run_performance_100k_v0.2.1.diff"
    [[ "$(sha256sum "$RUNNER_SRC" | awk '{print $1}')" == "$RUNNER_EXPECTED_SHA" ]] || fail "runner payload SHA mismatch"
    [[ "$(sha256sum "$DOC_SRC" | awk '{print $1}')" == "$DOC_EXPECTED_SHA" ]] || fail "design payload SHA mismatch"

    mkdir -p "$SCRIPT_ROOT" "$DOC_ROOT" "$META_ROOT"
    install_exact "$RUNNER_SRC" "$RUNNER_DST" 755
    install_exact "$DOC_SRC" "$DOC_DST" 644
    install_exact "$SELF_SOURCE" "$SELF_DST" 755
    install_exact "$DIFF_SRC" "$META_ROOT/rnatr_stage15a_run_performance_100k_v0.2.1.diff" 644
    install_exact "$BUNDLE_DIR/SHA256SUMS" "$META_ROOT/payload_SHA256SUMS" 644

    "$PYTHON_BIN" -m py_compile "$RUNNER_DST"

    {
        echo "timestamp_utc=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
        echo "host=$(hostname)"
        echo "uname=$(uname -a)"
        echo "python=$PYTHON_BIN"
        "$PYTHON_BIN" - <<'PY'
import os, platform, pysam, sys
print(f"python_version={sys.version.split()[0]}")
print(f"pysam_version={pysam.__version__}")
print(f"os_cpu_count={os.cpu_count()}")
print(f"platform={platform.platform()}")
PY
        echo "nproc=$(nproc)"
        free -h || true
        df -h "$PROJECT_ROOT" || true
        lscpu || true
    } > "$META_ROOT/host_environment.txt" 2>&1

    "$PYTHON_BIN" "$PROJECT_ROOT/metadata/ssot/rnatr_ssot.py" \
        --project-root "$PROJECT_ROOT" validate \
        > "$META_ROOT/ssot_validate.before.log"

    {
        printf 'role\tpath\tbytes\tsha256\n'
        for item in \
            "SELF_EXTRACTOR|$SELF_DST" \
            "RUNNER|$RUNNER_DST" \
            "DESIGN|$DOC_DST" \
            "RUNNER_DIFF|$META_ROOT/rnatr_stage15a_run_performance_100k_v0.2.1.diff" \
            "V0201_BASELINE_QC|$V0201_QC"
        do
            local role path
            role="${item%%|*}"
            path="${item#*|}"
            printf '%s\t%s\t%s\t%s\n' \
                "$role" "$path" "$(stat -c '%s' "$path")" "$(sha256sum "$path" | awk '{print $1}')"
        done
    } > "$META_ROOT/installation_manifest.tsv"
    sha256sum "$META_ROOT/installation_manifest.tsv" > "$META_ROOT/installation_manifest.tsv.sha256"

    echo "===== Stage 15A performance critical path v0.2.1 ====="
    echo "Python:                  $PYTHON_BIN"
    echo "CPUs:                    $CPU_COUNT"
    echo "Plan:                    12 shards x 2 caller workers"
    echo "Shard BAM index:         NOT CREATED"
    echo "Full development audits: OUTSIDE PRODUCTION TIMER, STILL REQUIRED"
    echo "Frozen final validators: INSIDE PRODUCTION TIMER"
    echo "Active pipeline switch:  PROHIBITED"
    echo "SSOT modification:       PROHIBITED"
    echo "Full 5.31M:              PROHIBITED"

    "$PYTHON_BIN" "$RUNNER_DST" --shards 12 --caller-workers-per-shard 2

    "$PYTHON_BIN" "$PROJECT_ROOT/metadata/ssot/rnatr_ssot.py" \
        --project-root "$PROJECT_ROOT" validate \
        > "$META_ROOT/ssot_validate.after.log"
}

