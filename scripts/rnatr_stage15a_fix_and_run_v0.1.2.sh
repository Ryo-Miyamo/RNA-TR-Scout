#!/usr/bin/env bash
set -euo pipefail

EXPECTED_PAYLOAD_SHA256="b55151ee5a5c922dcce1e0a82af2df0b31feb9d2631c6af20cea84f865032c02"
BUNDLE_NAME="rnatr_stage15a_fix_bundle_v0.1.2"
SELF_PATH="$(readlink -f "$0")"
TMPDIR_STAGE15A="$(mktemp -d)"

cleanup() {
    rm -rf "$TMPDIR_STAGE15A"
}
trap cleanup EXIT

PAYLOAD_LINE="$(awk '/^__RNATR_STAGE15A_PAYLOAD_BELOW__$/ {print NR + 1; exit}' "$0")"
if [[ -z "$PAYLOAD_LINE" ]]; then
    echo "ERROR: embedded payload marker not found" >&2
    exit 1
fi

PAYLOAD_TAR="$TMPDIR_STAGE15A/${BUNDLE_NAME}.tar.gz"
tail -n "+$PAYLOAD_LINE" "$0" | base64 --decode > "$PAYLOAD_TAR"

OBSERVED_SHA256="$(sha256sum "$PAYLOAD_TAR" | awk '{print $1}')"
if [[ "$OBSERVED_SHA256" != "$EXPECTED_PAYLOAD_SHA256" ]]; then
    echo "ERROR: embedded payload SHA-256 mismatch" >&2
    echo "expected: $EXPECTED_PAYLOAD_SHA256" >&2
    echo "observed: $OBSERVED_SHA256" >&2
    exit 1
fi

tar -xzf "$PAYLOAD_TAR" -C "$TMPDIR_STAGE15A"
cd "$TMPDIR_STAGE15A/$BUNDLE_NAME"
sha256sum -c SHA256SUMS
export RNATR_STAGE15A_SELF="$SELF_PATH"
bash ./install_and_run_stage15a_reference_v0.1.2.sh
exit 0

