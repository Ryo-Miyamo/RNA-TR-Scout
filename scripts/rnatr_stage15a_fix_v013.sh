fail() {
    echo "ERROR: $*" >&2
    exit 1
}

require_file() {
    [[ -s "$1" ]] || fail "required file missing or empty: $1"
}

check_sha() {
    local path="$1"
    local expected="$2"
    local observed
    require_file "$path"
    observed="$(sha256sum "$path" | awk '{print $1}')"
    [[ "$observed" == "$expected" ]] || {
        fail "SHA-256 mismatch for $path (expected $expected, observed $observed)"
    }
}

install_versioned() {
    local role="$1"
    local source="$2"
    local destination="$3"
    local mode="$4"
    local source_sha destination_sha status

    require_file "$source"
    source_sha="$(sha256sum "$source" | awk '{print $1}')"
    mkdir -p "$(dirname "$destination")"

    if [[ -e "$destination" ]]; then
        destination_sha="$(sha256sum "$destination" | awk '{print $1}')"
        if [[ "$destination_sha" == "$source_sha" ]]; then
            status="ALREADY_IDENTICAL"
        else
            fail "versioned destination exists with different content: $destination"
        fi
    else
        cp "$source" "$destination"
        chmod "$mode" "$destination"
        status="INSTALLED"
    fi

    printf '%s	%s	%s	%s	%s	%s
'         "$role" "$source" "$destination"         "$(stat -c '%s' "$destination")" "$source_sha" "$status"         >> "$INSTALL_MANIFEST"
}

comparison_logical_pass() {
    local path="$1"
    require_file "$path"
    awk -F '	' '
        NR == 1 {
            for (i = 1; i <= NF; i++) {
                if ($i == "logical_equal") logical = i
                if ($i == "candidate_rows") candidate = i
                if ($i == "reference_rows") reference = i
                if ($i == "header_equal") header = i
            }
            if (!logical || !candidate || !reference || !header) exit 2
            next
        }
        $logical != "true" || $candidate != $reference || ($header != "true" && $header != ".") { bad = 1 }
        END { exit bad }
    ' "$path" || fail "semantic parity is not PASS in $path"
}

