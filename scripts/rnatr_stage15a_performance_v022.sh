install_exact() {
    local source="$1"
    local destination="$2"
    local mode="$3"
    local source_sha destination_sha temporary
    source_sha="$(sha256sum "$source" | awk '{print $1}')"
    mkdir -p "$(dirname "$destination")"
    if [[ -e "$destination" ]]; then
        destination_sha="$(sha256sum "$destination" | awk '{print $1}')"
        [[ "$source_sha" == "$destination_sha" ]] || {
            echo "ERROR: versioned destination exists with different SHA: $destination" >&2
            return 1
        }
        chmod "$mode" "$destination"
        return 0
    fi
    temporary="${destination}.installing.$$"
    cp "$source" "$temporary"
    chmod "$mode" "$temporary"
    mv "$temporary" "$destination"
}

